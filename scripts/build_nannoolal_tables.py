"""Generate ``rsstatchem/core/chem_draw/nannoolal_tables.py`` from the Nannoolal / Rarey
group-contribution parameter files published by DDBST (Dortmund Data Bank Software &
Separation Technology GmbH) for the textbook J. Gmehling, B. Kolbe, M. Kleiber, J. Rarey,
"Chemical Thermodynamics for Process Simulation" (Wiley-VCH 2012):

    https://chemthermo.ddbst.com/Parameters/default.html
    2012-01-18 Rarey-Nannoolal {Tb, Tcri, Pcri, vcri, Vap}.txt

("Parameters (revised and extended - 2012-01-18)"; the page says the methods are meant to be
implemented in computer software). Their first-order, correction and interaction values for
Tc, Pc, Vc and the vapour-pressure slope dB are the values tabulated in Y. Nannoolal, PhD
thesis, University of KwaZulu-Natal 2006 (http://hdl.handle.net/10413/3766, Appendix C) and
reproduce its worked examples (Appendix D); the normal-boiling-point file has the group values
of Nannoolal et al., Fluid Phase Equilib. 226 (2004) 45 with revised equation constants.

    python scripts/build_nannoolal_tables.py --download   # -> build/nannoolal-raw/*.txt
    python scripts/build_nannoolal_tables.py              # writes the module

Numbering: the Tb file calls the C=C-C=O correction 118 and has an unexplained entry
134 ("empty"); the other files call it 134 and list 118 (1,2-diketone, "not use") as 0. The
module stores the C=C-C=O correction as 134 for every property and drops the Tb "empty" entry.
A first-order value of 0 (or a blank) means "not regressed": the property is then not
estimated for molecules with that group. 0 for a correction or interaction means no effect.
"""
from __future__ import annotations

import argparse
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "build" / "nannoolal-raw"
OUT = ROOT / "rsstatchem" / "core" / "chem_draw" / "nannoolal_tables.py"
BASE = "https://chemthermo.ddbst.com/Parameters/"
FILES = {"tb": "2012-01-18 Rarey-Nannoolal Tb.txt", "tc": "2012-01-18 Rarey-Nannoolal Tcri.txt",
         "pc": "2012-01-18 Rarey-Nannoolal Pcri.txt", "vc": "2012-01-18 Rarey-Nannoolal vcri.txt",
         "db": "2012-01-18 Rarey-Nannoolal Vap.txt"}
FIRST_ORDER = set(range(1, 118)) | {214, 215, 216}


def download(raw: Path) -> None:
    raw.mkdir(parents=True, exist_ok=True)
    try:
        import certifi
        import ssl
        ctx = ssl.create_default_context(cafile=certifi.where())
    except ImportError:
        ctx = None
    for name in FILES.values():
        url = urllib.parse.urljoin(BASE, urllib.parse.quote(name))
        req = urllib.request.Request(url, headers={"User-Agent": "RS-StatChem build"})
        data = urllib.request.urlopen(req, timeout=120, context=ctx).read()
        (raw / name).write_bytes(data)
        print(f"{url} -> {len(data)} bytes")


def parse(path: Path, prop: str):
    text = path.read_text(encoding="latin-1")
    sec1 = text.split("1) Equation Parameter")[1].split("2) Group Contribution")[0]
    params = [float(x) for x in re.findall(r"^\s*(-?\d+\.\d+)\s*$", sec1, re.M)]
    sec2 = text.split("2) Group Contribution Values")[1].split("3) Interaction")[0]
    sec3 = text.split("3) Interaction Contributions")[1].split("4) Interaction Groups")[0]
    groups: dict[int, float | None] = {}
    for line in sec2.splitlines():
        m = re.match(r"^(\d+)\s+(-?\d*\.?\d*)\s*(.*)$", line)
        if not m:
            continue
        gid, val = int(m.group(1)), m.group(2)
        if val in ("", "."):
            v = None
        else:
            v = float(val)
        if prop == "tb" and gid == 134:          # "empty" (see the module docstring)
            continue
        if prop == "tb" and gid == 118:          # Tb numbering of the C=C-C=O correction
            gid = 134
        if prop != "tb" and gid == 118:          # 1,2-diketone, "not use"
            continue
        if gid in FIRST_ORDER and v == 0.0:
            v = None
        groups[gid] = v
    inter: dict[tuple, float] = {}
    for line in sec3.splitlines():
        m = re.match(r"^(\d+)\s+(-?\d+\.?\d*)\s+(\S+(?:\(a\))?)\s*-\s*(\S+(?:\(a\))?)", line)
        if m:
            inter[(m.group(3), m.group(4))] = float(m.group(2))
    return params, groups, inter


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--raw", type=Path, default=RAW)
    ap.add_argument("--download", action="store_true")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    if args.download:
        download(args.raw)
    tables = {p: parse(args.raw / f, p) for p, f in FILES.items()}
    lines = ['# ruff: noqa: E501 - generated data rows',
             '"""Nannoolal / Rarey group-contribution parameters (generated by',
             'scripts/build_nannoolal_tables.py from the DDBST parameter files of 2012-01-18;',
             'do not edit by hand). See :mod:`rsstatchem.core.chem_draw.nannoolal` for the methods and',
             'sources. ``None`` = no regressed value (the property is not estimated)."""',
             "", "from __future__ import annotations", "",
             '__all__ = ["PARAMS", "GROUPS", "INTERACTIONS"]', "",
             "# equation constants as listed in each file",
             "PARAMS: dict[str, tuple] = {"]
    for p, (params, _g, _i) in tables.items():
        lines.append(f"    {p!r}: {tuple(params)!r},")
    lines += ["}", "", "# property -> {group id: contribution}", "GROUPS: dict[str, dict] = {"]
    for p, (_pa, groups, _i) in tables.items():
        lines.append(f"    {p!r}: {{")
        for gid in sorted(groups):
            lines.append(f"        {gid}: {groups[gid]!r},")
        lines.append("    },")
    lines += ["}", "", "# property -> {(interaction group, interaction group): contribution}",
              "INTERACTIONS: dict[str, dict] = {"]
    for p, (_pa, _g, inter) in tables.items():
        lines.append(f"    {p!r}: {{")
        for k in inter:
            lines.append(f"        {k!r}: {inter[k]!r},")
        lines.append("    },")
    lines.append("}")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for p, (params, groups, inter) in tables.items():
        n_ok = sum(1 for g, v in groups.items() if v is not None and g in FIRST_ORDER)
        print(f"{p}: params {params}, {n_ok} first-order values, {len(groups)} entries, "
              f"{len(inter)} interactions")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
